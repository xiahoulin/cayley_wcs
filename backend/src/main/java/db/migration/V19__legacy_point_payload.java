    @Override public void migrate(Context context) throws Exception { migrate(context.getConnection()); }
    public void migrate(Connection connection) throws Exception {
        try (Statement sql = connection.createStatement()) {
            sql.execute("alter table wcs_task_chain add column original_segments text");
            sql.execute("alter table wcs_task_chain add column held_reason varchar(1024)");
            sql.execute("create table wcs_contract_migration_audit (id bigint generated by default as identity primary key, entity_type varchar(32) not null, entity_id bigint not null, action varchar(64) not null, details text not null, tenant_id bigint not null, create_time timestamp(6) not null default current_timestamp)");
        }
        migrateApplications(connection);
        migrateTasks(connection);
        migrateChains(connection);
        try (Statement sql = connection.createStatement(); ResultSet rows = sql.executeQuery("select id,tenant_id,protocol_code from wcs_protocol where lifecycle_state='draft' and is_valid=true")) {
            while (rows.next()) audit(connection,"protocol",rows.getLong("id"),"await_publication",Map.of("protocol_code",rows.getString("protocol_code"),"reason","协议须显式发布，旧绑定未自动授予兼容性"),rows.getLong("tenant_id"));
        }
    }

    private void migrateApplications(Connection connection) throws Exception {
        String query = "select a.id,a.tenant_id,a.app_code,p.protocol_code from wcs_application a join wcs_protocol p on p.id=a.protocol_id where a.direction='upstream' and a.device_type='none' and a.is_valid=true";
        try (Statement statement = connection.createStatement(); ResultSet rows = statement.executeQuery(query)) {
            while (rows.next()) {
                long id=rows.getLong("id"),tenant=rows.getLong("tenant_id"); String app=rows.getString("app_code"),oldProtocol=rows.getString("protocol_code");
                boolean known = "WMS-MAIN".equals(app) || "TOKEN-LINK-20261012".equals(app) || app.startsWith("TOKEN-LINK-");
                if (known && "STACKER_STD".equals(oldProtocol)) {
                    Long replacement = nullableId(connection,"select id from wcs_protocol where protocol_code='HTTP_DEVICE_CONTRACT' and tenant_id=? and is_valid=true",tenant);
                    if (replacement != null) try (PreparedStatement update=connection.prepareStatement("update wcs_application set protocol_id=?,protocol_revision_id=null,configuration_state='awaiting_contract' where id=?")) {
                        update.setLong(1,replacement); update.setLong(2,id); update.executeUpdate();
                        audit(connection,"application",id,"http_protocol_reclassified",Map.of("old_protocol",oldProtocol,"new_protocol","HTTP_DEVICE_CONTRACT","reason","上位HTTP身份明确；待显式发布、选定版本及重新授予关系"),tenant);
                    }
                } else audit(connection,"application",id,"manual_classification_required",Map.of("reason","未明确的上位协议关系不自动改写"),tenant);
            }
        }
    }

    private void migrateTasks(Connection connection) throws Exception {
        String select = "select t.*,a.device_type,c.upstream_app_id as chain_upstream from wcs_task t left join wcs_application a on a.id=t.app_id left join wcs_task_chain c on c.id=t.chain_id";
        try (Statement statement = connection.createStatement(); ResultSet rows = statement.executeQuery(select)) {
            while (rows.next()) {
                long id=rows.getLong("id"),tenant=rows.getLong("tenant_id");
                Map<String,Object> original = new LinkedHashMap<>();
                original.put("taskNo",rows.getString("task_no")); original.put("appId",rows.getLong("app_id")); original.put("task_type",rows.getString("task_type"));
                for (String column : COORDINATES.keySet()) original.put(column,rows.getLong(column));
                String rawPayload=rows.getString("payload"); Map<String,Object> payload;
                List<String> reasons=new ArrayList<>();
                try { payload=object(rawPayload); original.put("payload",redact(payload)); }
                catch (Exception ex) { payload=null; original.put("payload_parse_error",true); reasons.add("历史payload不是合法JSON对象，原列完整保留"); }
                Map<String,Object> normalized=null;
                if (payload != null) try { normalized=convert(template(rows.getString("device_type")),original,payload); }
                catch (IllegalArgumentException ex) { reasons.add(ex.getMessage()); }
                Long caller = nullableLong(rows,"caller_app_id");
                Long chainCaller=nullableLong(rows,"chain_upstream");
                if (caller == null && chainCaller != null && chainCaller > 0) caller=chainCaller;
                if (caller == null) reasons.add("独立历史任务缺少可信调用方，待核对来源");
                String status=rows.getString("status"),step=rows.getString("handshake_step");
                boolean physicalEvidence=rows.getTimestamp("dispatch_time")!=null || step!=null && Set.of("PARAMS_WRITTEN","EXECUTE_CONFIRMED","EXECUTING","COMPLETE_CONFIRMED","CLEARED","MOVING","COMMANDING").contains(step.toUpperCase(Locale.ROOT));
                boolean physicallyStarted=rows.getBoolean("physical_started") || "dispatched".equals(status) || "executing".equals(status)
                        || "failed".equals(status) && physicalEvidence;
                Long nativeNumber=nullableLong(rows,"native_task_num");
                String device=template(rows.getString("device_type"));
                if (physicallyStarted && Set.of("stacker","conveyor","lift").contains(device) && nativeNumber == null) {
                    String digits=rows.getString("task_no")==null ? "" : rows.getString("task_no").replaceAll("\\D","");
                    try { long number=Long.parseLong(digits); if (number < 1) throw new NumberFormatException(); nativeNumber=number; }
                    catch (NumberFormatException ex) { reasons.add("旧在飞设备任务号无法明确恢复，禁止重新编号"); }
                }
                if (!TERMINAL.contains(status)) reasons.add("旧任务协议版本与绑定尚未核对，待排空或受控转换");
                if (physicallyStarted) reasons.add("旧物理作业可能尚未确认收尾，保留原映射并禁止自动接管");
                String prior=rows.getString("held_reason"); if (prior != null && !prior.isBlank()) reasons.add(0,prior);
                String held=limit(String.join("；",new LinkedHashSet<>(reasons)));
                String scope=rows.getString("idempotency_scope"); if (scope==null || scope.isBlank()) scope="legacy:"+id;
                try (PreparedStatement update=connection.prepareStatement("update wcs_task set original_request=?,payload=?,caller_app_id=?,native_task_num=?,physical_started=?,held_reason=?,idempotency_scope=? where id=?")) {
                    update.setString(1,JSON.writeValueAsString(original)); update.setString(2,normalized==null?rawPayload:JSON.writeValueAsString(normalized));
                    nullable(update,3,caller); nullable(update,4,nativeNumber); update.setBoolean(5,physicallyStarted); update.setString(6,held); update.setString(7,scope); update.setLong(8,id); update.executeUpdate();
                }
                audit(connection,"task",id,normalized==null?"payload_conversion_held":"payload_converted",Map.of("template",device,"reason",held,"original_field_names",original.keySet(),"payload_field_names",payload==null?List.of():payload.keySet(),"legacy_scope",scope,"physical_started",physicallyStarted),tenant);
            }
        }
    }

    private void migrateChains(Connection connection) throws Exception {
        try (Statement statement=connection.createStatement(); ResultSet rows=statement.executeQuery("select id,tenant_id,status,segments from wcs_task_chain")) {
            while (rows.next()) {
                long id=rows.getLong("id"),tenant=rows.getLong("tenant_id"); String raw=rows.getString("segments");
                List<Map<String,Object>> originals=null,converted=new ArrayList<>(); List<String> reasons=new ArrayList<>();
                try {
                    originals=JSON.readValue(raw,SEGMENTS);
                    for (Map<String,Object> segment:originals) {
                        Set<Long> appIds=new LinkedHashSet<>(); if (segment.get("appId") instanceof Number app) appIds.add(app.longValue());
                        if (segment.get("candidateAppIds") instanceof List<?> candidates) for (Object candidate:candidates) { if (!(candidate instanceof Number app)) throw new IllegalArgumentException("候选应用ID不是整数"); appIds.add(app.longValue()); }
                        if (appIds.isEmpty()) throw new IllegalArgumentException("链段没有明确目标应用");
                        Set<String> templates=new LinkedHashSet<>(); for (Long appId:appIds) {
                            String type=null;
                            try (PreparedStatement query=connection.prepareStatement("select device_type from wcs_application where id=? and tenant_id=? and is_valid=true")) { query.setLong(1,appId); query.setLong(2,tenant); try(ResultSet app=query.executeQuery()){ if(app.next())type=app.getString(1); } }
                            templates.add(template(type));
                        }
                        if (templates.size()!=1 || templates.contains("unknown")) throw new IllegalArgumentException("链段候选应用模板不一致或未实现");
                        Map<String,Object> flat=new LinkedHashMap<>(); flat.put("task_type",segment.get("taskType"));
                        SEGMENT_COORDINATES.forEach((oldKey,column)->flat.put(column,segment.getOrDefault(oldKey,0)));
                        Object oldPayload=segment.getOrDefault("payload",Map.of()); if (!(oldPayload instanceof Map<?,?>)) throw new IllegalArgumentException("链段payload不是点位对象");
                        @SuppressWarnings("unchecked") Map<String,Object> payload=(Map<String,Object>)oldPayload;
                        Map<String,Object> mapped=new LinkedHashMap<>(segment); mapped.put("payload",convert(templates.iterator().next(),flat,payload));
                        mapped.remove("taskType"); SEGMENT_COORDINATES.keySet().forEach(mapped::remove); converted.add(mapped);
                    }
                } catch (Exception ex) { reasons.add("历史链段转换待核对: "+ex.getMessage()); converted=null; }
                if (!TERMINAL.contains(rows.getString("status"))) reasons.add("历史链协议版本与候选绑定待核对，禁止在新地址自动物化");
                String original=originals==null?null:JSON.writeValueAsString(redact(originals));
                try (PreparedStatement update=connection.prepareStatement("update wcs_task_chain set original_segments=?,segments=?,held_reason=? where id=?")) {
                    update.setString(1,original); update.setString(2,converted==null?raw:JSON.writeValueAsString(converted)); update.setString(3,limit(String.join("；",reasons))); update.setLong(4,id); update.executeUpdate();
                }
                audit(connection,"chain",id,converted==null?"segments_conversion_held":"segments_converted",Map.of("reason",limit(String.join("；",reasons)),"converted_segment_count",converted==null?0:converted.size()),tenant);
            }
        }
    }

    public static Map<String,Object> convert(String template, Map<String,Object> flat, Map<String,Object> payload) {
        Map<String,Object> result=new LinkedHashMap<>(payload); Set<String> allowed;
        switch(template) {
            case "stacker" -> {
                COORDINATES.forEach((column,field)->merge(result,field,flat.getOrDefault(column,0)));
                Object type=flat.get("task_type"); if(type==null || type.toString().isBlank()) throw new IllegalArgumentException("历史堆垛机任务类型无法确定");
                try { merge(result,"cmd_TaskType",new BigDecimal(type.toString()).longValueExact()); } catch(ArithmeticException | NumberFormatException ex) { throw new IllegalArgumentException("历史堆垛机任务类型不是有效整数"); }
                allowed=Set.of("cmd_TaskType","cmd_TakeCoor_Row","cmd_TakeCoor_Column","cmd_TakeCoor_Floor","cmd_PutCoor_Row","cmd_PutCoor_Column","cmd_PutCoor_Floor","cmd_PortNum");
            }
            case "conveyor" -> { alias(result,"toStation","cmd_DestStation"); result.remove("fromStation"); allowed=Set.of("cmd_DestStation"); }
            case "lift" -> { alias(result,"targetFloor","cmd_TargetFloor"); allowed=Set.of("cmd_TargetFloor"); }
            case "auto_door" -> {
                Object action=result.remove("action");
                if(action!=null) { String command=action.toString().toLowerCase(Locale.ROOT); if(!Set.of("open","close").contains(command)) throw new IllegalArgumentException("未知历史自动门action，禁止默认开门"); merge(result,"cmd_Open","open".equals(command)?1:0); merge(result,"cmd_Close","close".equals(command)?1:0); }
                allowed=Set.of("cmd_Open","cmd_Close");
            }
            default -> throw new IllegalArgumentException("历史任务设备类型未实现，保留原payload");
        }
        Set<String> unknown=new LinkedHashSet<>(result.keySet()); unknown.removeAll(allowed);
        if(!unknown.isEmpty()) throw new IllegalArgumentException("历史payload存在未定义点位: "+unknown);
        if(!result.keySet().containsAll(allowed)) throw new IllegalArgumentException("历史payload缺少业务点位: "+difference(allowed,result.keySet()));
        for(String field:allowed) {
            Object raw=result.get(field);
            try { long number=new BigDecimal(raw.toString()).longValueExact(); if(number<0)throw new ArithmeticException();result.put(field,number); }
            catch(RuntimeException ex) { throw new IllegalArgumentException("历史点位不是非负整数: "+field); }
        }
        if("auto_door".equals(template) && ((Long)result.get("cmd_Open")+(Long)result.get("cmd_Close")!=1 || (Long)result.get("cmd_Open")>1 || (Long)result.get("cmd_Close")>1))throw new IllegalArgumentException("历史自动门开关点位必须恰好一个为1");
        if("stacker".equals(template) && ((Long)result.get("cmd_TaskType")<1 || (Long)result.get("cmd_TaskType")>6))throw new IllegalArgumentException("历史堆垛机任务类型不在已实现范围");
        return result;
    }
    private static Set<String> difference(Set<String> source,Set<String> removed) { Set<String> result=new LinkedHashSet<>(source);result.removeAll(removed);return result; }
    private static void alias(Map<String,Object> values,String legacy,String canonical) { Object value=values.remove(legacy);if(value!=null)merge(values,canonical,value); }
    private static void merge(Map<String,Object> values,String field,Object value) {
        if(value==null)throw new IllegalArgumentException("历史字段为空: "+field);
        if(values.containsKey(field)) { Object old=values.get(field); if(!equal(old,value))throw new IllegalArgumentException("平铺/旧payload与新点位冲突: "+field); }
        else values.put(field,value);
    }
    private static boolean equal(Object a,Object b) { try{return new BigDecimal(a.toString()).compareTo(new BigDecimal(b.toString()))==0;}catch(RuntimeException ex){return java.util.Objects.equals(a,b);} }
    private static String template(String value) { if("palletizer".equals(value))return "stacker";return value!=null&&Set.of("stacker","conveyor","lift","auto_door").contains(value)?value:"unknown"; }
    private static Map<String,Object> object(String raw) throws Exception { return raw==null?new LinkedHashMap<>():JSON.readValue(raw,OBJECT); }
    private static Object redact(Object value) {
        if(value instanceof Map<?,?> map) { Map<String,Object> safe=new LinkedHashMap<>(); map.forEach((key,item)->{String field=String.valueOf(key);if(!field.toLowerCase(Locale.ROOT).matches(".*(secret|token|password|authorization|app_key).*"))safe.put(field,redact(item));});return safe; }
        if(value instanceof List<?> list)return list.stream().map(V19__legacy_point_payload::redact).toList();return value;
    }
    private static String limit(String value) { return value.length()>1024?value.substring(0,1024):value; }
    private static Long nullableId(Connection c,String query,long id) throws SQLException { try(PreparedStatement s=c.prepareStatement(query)){s.setLong(1,id);try(ResultSet row=s.executeQuery()){return row.next()?row.getLong(1):null;}} }
    private static Long nullableLong(ResultSet rows,String column) throws SQLException { long value=rows.getLong(column);return rows.wasNull()?null:value; }
    private static void nullable(PreparedStatement sql,int index,Long value) throws SQLException { if(value==null)sql.setNull(index,java.sql.Types.BIGINT);else sql.setLong(index,value); }
    private static void audit(Connection c,String type,long id,String action,Map<String,Object> details,long tenant) throws Exception {
        try(PreparedStatement sql=c.prepareStatement("insert into wcs_contract_migration_audit(entity_type,entity_id,action,details,tenant_id)values(?,?,?,?,?)")) {sql.setString(1,type);sql.setLong(2,id);sql.setString(3,action);sql.setString(4,JSON.writeValueAsString(details));sql.setLong(5,tenant);sql.executeUpdate();}
    }
