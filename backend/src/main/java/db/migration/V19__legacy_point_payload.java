    private static final Map<String,String> COORDINATES = Map.of("take_row","cmd_TakeCoor_Row","take_column","cmd_TakeCoor_Column","take_floor","cmd_TakeCoor_Floor","put_row","cmd_PutCoor_Row","put_column","cmd_PutCoor_Column","put_floor","cmd_PutCoor_Floor","port_num","cmd_PortNum");
